// Package ledger is the durable, append-only event store of the harness daemon.
//
// One SQLite file holds every stream. A single writer goroutine assigns per-stream
// sequences (gap-free, starting at 1) and a non-decreasing time, and commits each event
// with synchronous=FULL (plus fullfsync on darwin) before anyone can see it. Readers use
// a separate pool of query_only connections. The package imports no other internal
// package.
package ledger

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sync"
	"sync/atomic"
	"time"
)

// Event is one committed ledger entry.
type Event struct {
	Pos    int64           `json:"-"` // global commit order (rowid); internal
	Stream string          `json:"stream"`
	Seq    int64           `json:"seq"`
	ID     string          `json:"id"` // idempotency key; ULID unless the producer supplies one
	Type   string          `json:"type"`
	Time   Time            `json:"time"` // assigned inside the writer transaction; never decreases
	Data   json.RawMessage `json:"data"`
}

// NewEvent is an event offered to Append.
type NewEvent struct {
	Stream string          // ^[a-z][A-Za-z0-9_.:-]{0,127}$
	ID     string          // empty: a ULID is generated by Append before enqueueing; else ^[A-Za-z0-9_.:-]{1,64}$
	Type   string          // ^[a-z][a-z0-9_.:-]{0,127}$
	Data   json.RawMessage // valid JSON, at most 1 MiB, at least 2 bytes; empty is stored as {}
}

var (
	ErrInvalidStream   = errors.New("ledger: invalid stream id")
	ErrInvalidType     = errors.New("ledger: invalid event type")
	ErrInvalidID       = errors.New("ledger: invalid event id")
	ErrInvalidData     = errors.New("ledger: data is not valid JSON")
	ErrPayloadTooLarge = errors.New("ledger: data exceeds 1 MiB") // internal; not a wire code
	ErrIDConflict      = errors.New("ledger: id exists with different content")
	ErrClosed          = errors.New("ledger: closed")
	ErrSchemaAhead     = errors.New("ledger: schema newer than binary") // Open returns *SchemaAheadError, which wraps it
)

// Appender is served by exactly one writer goroutine per ledger.
//   - Validation happens in Append, before enqueueing; invalid events never reach the writer.
//   - ctx bounds only enqueueing (the queue holds 256; a full queue blocks) and waiting for
//     the result. The writer runs every transaction under its own lifetime context, so a
//     cancelled caller can never abort or half-apply a commit.
//   - The returned Event always carries the ID, even with an error, so a retry is idempotent.
//   - On success, the event is committed and synced, and OnCommit has been called.
type Appender interface {
	Append(ctx context.Context, e NewEvent) (ev Event, created bool, err error)
}

// Page is one bounded slice of a stream.
type Page struct {
	Events  []Event
	HasMore bool
}

// PageByteBudget bounds a page: the sum of len(Data) of its events. A page always holds
// at least one event.
const PageByteBudget = 8 << 20

// Reader reads committed history.
type Reader interface {
	// Read returns events with seq > after, ascending, at most limit, within PageByteBudget.
	Read(ctx context.Context, stream string, after int64, limit int) (Page, error)
	Head(ctx context.Context, stream string) (int64, error)       // 0 when empty
	Last(ctx context.Context, stream string) (Event, bool, error) // for unclean-shutdown detection
	Stats(ctx context.Context) (Stats, error)                     // streams, events, schema version
}

// Stats summarises the ledger.
type Stats struct {
	SchemaVersion int `json:"schema_version"`
	Streams       int `json:"streams"`
	Events        int `json:"events"`
}

// Options configure Open.
type Options struct {
	Path     string
	OnCommit func(Event) // called by the writer goroutine after COMMIT, in seq order; must not block

	// Test seams, reachable only from inside this package.
	clock func() time.Time // defaults to time.Now
	hooks hooks
}

// hooks let in-package tests hold the writer at precise points.
type hooks struct {
	schemaCheck   func(dsn string) // the DSN of the read-only schema-ahead check
	beforeDequeue func()           // writer: before it takes the next request; may block
	inTx          func(id string)  // writer: after the INSERT, before COMMIT; may block
}

// queueSize is how many appends may wait for the writer.
const queueSize = 256

// Ledger is an open ledger. Its zero value is not usable; call Open.
type Ledger struct {
	path     string
	onCommit func(Event)
	clock    func() time.Time
	hooks    hooks

	wdb *sql.DB // writer pool: one connection, BEGIN IMMEDIATE
	rdb *sql.DB // reader pool: query_only

	queue chan *request
	life  context.Context // the writer's own lifetime; cancelled only by a forced Close
	stop  context.CancelFunc
	done  chan struct{} // closed when the writer goroutine has returned
	last  time.Time     // last assigned time; owned by the writer goroutine

	closing      chan struct{} // closed first by Close: wakes blocked enqueuers
	closeStarted atomic.Bool   // set by the first Close
	mu           sync.RWMutex  // guards closed and every send on queue
	closed       bool
	finished     chan struct{} // closed when Close has completed
	closeErr     error         // written before finished is closed

	readersClosed bool // guarded by mu
}

var (
	_ Appender = (*Ledger)(nil)
	_ Reader   = (*Ledger)(nil)
)

// Open checks the schema version on a read-only connection first and returns
// *SchemaAheadError (which wraps ErrSchemaAhead) without writing anything if the database
// is newer than the embedded migrations; then it opens the writer and reader pools,
// migrates, and starts the writer.
func Open(ctx context.Context, opts Options) (*Ledger, error) {
	if opts.Path == "" {
		return nil, errors.New("ledger: path is required")
	}
	path, err := filepath.Abs(opts.Path)
	if err != nil {
		return nil, fmt.Errorf("ledger: %w", err)
	}

	if err := checkSchemaAhead(ctx, path, opts.hooks.schemaCheck); err != nil {
		return nil, err
	}
	if err := ensureFile(path); err != nil {
		return nil, err
	}

	l := &Ledger{
		path:     path,
		onCommit: opts.OnCommit,
		clock:    opts.clock,
		hooks:    opts.hooks,
		queue:    make(chan *request, queueSize),
		done:     make(chan struct{}),
		closing:  make(chan struct{}),
		finished: make(chan struct{}),
	}
	if l.clock == nil {
		l.clock = time.Now
	}

	if l.wdb, err = sql.Open(driverName, writerDSN(path)); err != nil {
		return nil, fmt.Errorf("ledger: open writer: %w", err)
	}
	// One connection, kept for the process lifetime: every pragma lives on it.
	l.wdb.SetMaxOpenConns(1)
	l.wdb.SetMaxIdleConns(1)
	l.wdb.SetConnMaxLifetime(0)

	fail := func(err error) (*Ledger, error) {
		if l.rdb != nil {
			l.rdb.Close()
		}
		l.wdb.Close()
		return nil, err
	}

	if err := migrate(ctx, l.wdb); err != nil {
		return fail(fmt.Errorf("ledger: migrate: %w", err))
	}

	if l.rdb, err = sql.Open(driverName, readerDSN(path)); err != nil {
		return fail(fmt.Errorf("ledger: open readers: %w", err))
	}
	l.rdb.SetMaxOpenConns(readerConns)
	l.rdb.SetMaxIdleConns(readerConns)
	l.rdb.SetConnMaxLifetime(0)

	if l.last, err = lastAssignedTime(ctx, l.wdb); err != nil {
		return fail(err)
	}

	l.life, l.stop = context.WithCancel(context.Background())
	go l.run()
	return l, nil
}

// checkSchemaAhead refuses a database written by a newer binary. It runs on a mode=ro
// connection and never touches a file that does not exist yet.
func checkSchemaAhead(ctx context.Context, path string, hook func(string)) error {
	info, err := os.Stat(path)
	switch {
	case errors.Is(err, os.ErrNotExist):
		return nil
	case err != nil:
		return fmt.Errorf("ledger: %w", err)
	case info.Size() == 0:
		return nil
	}
	v, err := readSchemaVersion(ctx, path, hook)
	if err != nil {
		return fmt.Errorf("ledger: read schema version: %w", err)
	}
	if v > binaryVersion {
		return &SchemaAheadError{DB: v, Binary: binaryVersion}
	}
	return nil
}

// ensureFile creates an absent database file as 0600 so the file, and the -wal and -shm
// files SQLite derives from its mode, are private whatever the umask. An existing file is
// never touched (Business Rule 28).
func ensureFile(path string) error {
	f, err := os.OpenFile(path, os.O_RDWR|os.O_CREATE|os.O_EXCL, 0o600)
	switch {
	case err == nil:
		return f.Close()
	case errors.Is(err, os.ErrExist):
		return nil
	default:
		return fmt.Errorf("ledger: create %s: %w", path, err)
	}
}

// lastAssignedTime initialises the time floor from the row with the highest pos.
func lastAssignedTime(ctx context.Context, db *sql.DB) (time.Time, error) {
	var s string
	err := db.QueryRowContext(ctx, `SELECT time FROM events ORDER BY pos DESC LIMIT 1`).Scan(&s)
	if errors.Is(err, sql.ErrNoRows) {
		return time.Time{}, nil
	}
	if err != nil {
		return time.Time{}, fmt.Errorf("ledger: last time: %w", err)
	}
	return parseTime(s)
}

// Close makes later Appends return ErrClosed, drains the queue, then closes the
// connections. If ctx ends first, the transaction in flight is aborted and the appends
// still queued fail with ErrClosed; the connections are closed either way and ctx's error
// is returned. Close is idempotent: later calls wait for the first and return its result,
// or ctx's error if ctx ends first. A caller that must know the close has really finished,
// whatever its own ctx says, waits on Closed.
func (l *Ledger) Close(ctx context.Context) error {
	if l.closeStarted.CompareAndSwap(false, true) {
		l.closeErr = l.shutdown(ctx)
		close(l.finished)
		return l.closeErr
	}
	select {
	case <-l.finished:
		return l.closeErr
	case <-ctx.Done():
		return ctx.Err()
	}
}

// Closed returns a channel that is closed when the first Close has completed: the writer
// has returned, and the reader and writer connections are closed, so this process no longer
// writes harness.db (a close that ran out of time included: it finishes by aborting the
// transaction in flight). A second Close whose ctx has already ended returns at once while
// the first is still running; Closed is how that caller waits for it. Before any Close, the
// channel stays open.
func (l *Ledger) Closed() <-chan struct{} { return l.finished }

func (l *Ledger) shutdown(ctx context.Context) error {
	close(l.closing) // wake enqueuers blocked on a full queue
	l.mu.Lock()
	l.closed = true
	close(l.queue) // safe: every send holds mu.RLock and re-checks closed
	l.mu.Unlock()

	var drainErr error
	select {
	case <-l.done:
	case <-ctx.Done():
		l.stop()
		<-l.done
		drainErr = fmt.Errorf("ledger: drain interrupted: %w", ctx.Err())
	}
	l.stop()

	l.mu.Lock()
	l.readersClosed = true
	l.mu.Unlock()
	return errors.Join(drainErr, l.rdb.Close(), l.wdb.Close())
}

// readable reports ErrClosed once the reader pool is gone.
func (l *Ledger) readable() error {
	l.mu.RLock()
	defer l.mu.RUnlock()
	if l.readersClosed {
		return ErrClosed
	}
	return nil
}
